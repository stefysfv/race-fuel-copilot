const BY_KEY = new Map(FOOD_LIBRARY.map((item) => [item.key, item]));

export function libraryFoodByKey(key) {
  return BY_KEY.get(key) || null;
}

export function searchFoodLibrary(query, scope = "all", limit = 7) {
  const q = String(query || "").trim().toLowerCase();
  if (!q) return [];
  const scored = [];
  for (const item of FOOD_LIBRARY) {
    if (scope !== "all" && !item.scopes.includes(scope)) continue;
    const name = item.name.toLowerCase();
    const aliases = item.aliases.map((a) => a.toLowerCase());
    let score = 0;
    if (name === q || aliases.includes(q)) score = 100;
    else if (name.startsWith(q)) score = 85;
    else if (aliases.some((a) => a.startsWith(q))) score = 75;
    else if (name.split(/[\s/]+/).some((w) => w.startsWith(q))) score = 68;
    else if (name.includes(q)) score = 55;
    else if (aliases.some((a) => a.includes(q))) score = 45;
    if (score > 0) scored.push({ item, score });
  }
  scored.sort((a, b) => b.score - a.score || a.item.name.localeCompare(b.item.name));
  return scored.slice(0, limit).map((entry) => entry.item);
}
